-- 6.1 Recalculates subtotal, IVA and total for a sales order,
--     based on its detail lines.
CREATE OR REPLACE PROCEDURE sp_calculate_order_totals (
    p_order_id IN NUMBER
)
IS
    v_subtotal NUMBER(12,2);
    v_iva      NUMBER(12,2);
BEGIN
    SELECT NVL(SUM(quantity * unit_price), 0)
    INTO   v_subtotal
    FROM   sales_order_details
    WHERE  order_id = p_order_id;

    v_iva := fn_calculate_iva(v_subtotal);

    UPDATE sales_orders
    SET    subtotal     = v_subtotal,
           iva_amount   = v_iva,
           total_amount = v_subtotal + v_iva
    WHERE  order_id = p_order_id;

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20001, 'Error calculating order totals: ' || SQLERRM);
END sp_calculate_order_totals;
/

-- 6.2 Generates an invoice from a confirmed sales order.
CREATE OR REPLACE PROCEDURE sp_generate_invoice (
    p_order_id IN NUMBER
)
IS
    v_subtotal NUMBER(12,2);
    v_iva      NUMBER(12,2);
    v_total    NUMBER(12,2);
    v_invoice_number VARCHAR2(30);
BEGIN
    sp_calculate_order_totals(p_order_id);

    SELECT subtotal, iva_amount, total_amount
    INTO   v_subtotal, v_iva, v_total
    FROM   sales_orders
    WHERE  order_id = p_order_id;

    v_invoice_number := 'INV-' || TO_CHAR(SYSDATE, 'YYYYMMDD') || '-' || p_order_id;

    INSERT INTO invoices (order_id, invoice_number, invoice_date, subtotal, iva_amount, total_amount)
    VALUES (p_order_id, v_invoice_number, SYSDATE, v_subtotal, v_iva, v_total);

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20002, 'Error generating invoice: ' || SQLERRM);
END sp_generate_invoice;
/

-- 6.3 Sales report between two dates, grouped by product.
--     Returns an open cursor (REF CURSOR) to be consumed by the app layer.
CREATE OR REPLACE PROCEDURE sp_sales_report (
    p_start_date IN DATE,
    p_end_date   IN DATE,
    p_cursor     OUT SYS_REFCURSOR
)
IS
BEGIN
    OPEN p_cursor FOR
        SELECT p.product_id,
               p.product_name,
               c.category_name,
               SUM(d.quantity)               AS units_sold,
               SUM(d.quantity * d.unit_price) AS total_sales
        FROM   sales_order_details d
        JOIN   sales_orders o   ON o.order_id = d.order_id
        JOIN   products p       ON p.product_id = d.product_id
        JOIN   categories c     ON c.category_id = p.category_id
        WHERE  o.order_date BETWEEN p_start_date AND p_end_date
        AND    o.order_status <> 'CANCELLED'
        GROUP BY p.product_id, p.product_name, c.category_name
        ORDER BY total_sales DESC;
END sp_sales_report;
/

-- 6.4 Accounting trial balance (sum of debits/credits per account).
CREATE OR REPLACE PROCEDURE sp_trial_balance (
    p_cursor OUT SYS_REFCURSOR
)
IS
BEGIN
    OPEN p_cursor FOR
        SELECT a.account_code,
               a.account_name,
               a.account_type,
               NVL(SUM(d.debit_amount), 0)  AS total_debit,
               NVL(SUM(d.credit_amount), 0) AS total_credit,
               NVL(SUM(d.debit_amount), 0) - NVL(SUM(d.credit_amount), 0) AS balance
        FROM   chart_of_accounts a
        LEFT JOIN journal_entry_details d ON d.account_id = a.account_id
        GROUP BY a.account_code, a.account_name, a.account_type
        ORDER BY a.account_code;
END sp_trial_balance;
/

