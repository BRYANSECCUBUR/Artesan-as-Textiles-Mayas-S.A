-- ==========================================================================
-- 1. INVENTORY MODULE
-- ==========================================================================

CREATE TABLE categories (
    category_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name   VARCHAR2(100)  NOT NULL,
    description     VARCHAR2(255)
);

CREATE TABLE artisans (
    artisan_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name         VARCHAR2(150) NOT NULL,
    cooperative_name  VARCHAR2(150),
    region            VARCHAR2(100),
    phone             VARCHAR2(20),
    email             VARCHAR2(100)
);

CREATE TABLE products (
    product_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name     VARCHAR2(150)  NOT NULL,
    description      VARCHAR2(500),
    category_id      NUMBER         NOT NULL,
    artisan_id       NUMBER,
    unit_price       NUMBER(10,2)   NOT NULL,
    unit_cost        NUMBER(10,2),
    stock_quantity   NUMBER         DEFAULT 0 NOT NULL,
    reorder_level    NUMBER         DEFAULT 5,
    unit_of_measure  VARCHAR2(20)   DEFAULT 'UNIT',
    product_status   VARCHAR2(20)   DEFAULT 'ACTIVE',
    created_at       DATE           DEFAULT SYSDATE,
    CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES categories(category_id),
    CONSTRAINT fk_products_artisan  FOREIGN KEY (artisan_id)  REFERENCES artisans(artisan_id),
    CONSTRAINT ck_products_price    CHECK (unit_price >= 0),
    CONSTRAINT ck_products_stock    CHECK (stock_quantity >= 0),
    CONSTRAINT ck_products_status   CHECK (product_status IN ('ACTIVE','INACTIVE'))
);

CREATE TABLE inventory_movements (
    movement_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id      NUMBER        NOT NULL,
    movement_type   VARCHAR2(10)  NOT NULL,
    quantity        NUMBER        NOT NULL,
    movement_date   DATE          DEFAULT SYSDATE,
    reference_note  VARCHAR2(255),
    CONSTRAINT fk_movements_product FOREIGN KEY (product_id) REFERENCES products(product_id),
    CONSTRAINT ck_movements_type    CHECK (movement_type IN ('IN','OUT')),
    CONSTRAINT ck_movements_qty     CHECK (quantity > 0)
);

-- ==========================================================================
-- 2. SALES MODULE
-- ==========================================================================

CREATE TABLE customers (
    customer_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name       VARCHAR2(150) NOT NULL,
    email           VARCHAR2(100) UNIQUE,
    phone           VARCHAR2(20),
    address         VARCHAR2(255),
    country         VARCHAR2(100),
    customer_type   VARCHAR2(20)  DEFAULT 'NATIONAL',
    CONSTRAINT ck_customers_type CHECK (customer_type IN ('NATIONAL','INTERNATIONAL'))
);

CREATE TABLE sales_orders (
    order_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   NUMBER       NOT NULL,
    order_date    DATE         DEFAULT SYSDATE,
    order_status  VARCHAR2(20) DEFAULT 'PENDING',
    subtotal      NUMBER(12,2) DEFAULT 0,
    iva_amount    NUMBER(12,2) DEFAULT 0,
    total_amount  NUMBER(12,2) DEFAULT 0,
    CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id) REFERENCES customers(customer_id),
    CONSTRAINT ck_orders_status   CHECK (order_status IN ('PENDING','CONFIRMED','SHIPPED','CANCELLED'))
);

CREATE TABLE sales_order_details (
    detail_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       NUMBER       NOT NULL,
    product_id     NUMBER       NOT NULL,
    quantity       NUMBER       NOT NULL,
    unit_price     NUMBER(10,2) NOT NULL,
    line_subtotal  NUMBER(12,2),
    CONSTRAINT fk_details_order   FOREIGN KEY (order_id)   REFERENCES sales_orders(order_id),
    CONSTRAINT fk_details_product FOREIGN KEY (product_id) REFERENCES products(product_id),
    CONSTRAINT ck_details_qty     CHECK (quantity > 0)
);

