CREATE TABLE invoices (
    invoice_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        NUMBER        NOT NULL UNIQUE,
    invoice_number  VARCHAR2(30)  UNIQUE NOT NULL,
    invoice_date    DATE          DEFAULT SYSDATE,
    subtotal        NUMBER(12,2)  NOT NULL,
    iva_amount      NUMBER(12,2)  NOT NULL,
    total_amount    NUMBER(12,2)  NOT NULL,
    CONSTRAINT fk_invoices_order FOREIGN KEY (order_id) REFERENCES sales_orders(order_id)
);

CREATE TABLE chart_of_accounts (
    account_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_code  VARCHAR2(20)  UNIQUE NOT NULL,
    account_name  VARCHAR2(150) NOT NULL,
    account_type  VARCHAR2(20)  NOT NULL,
    CONSTRAINT ck_accounts_type CHECK (account_type IN ('ASSET','LIABILITY','EQUITY','INCOME','EXPENSE'))
);

CREATE TABLE journal_entries (
    entry_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_date     DATE          DEFAULT SYSDATE,
    description    VARCHAR2(255),
    reference_doc  VARCHAR2(50)
);

CREATE TABLE journal_entry_details (
    entry_detail_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id         NUMBER       NOT NULL,
    account_id       NUMBER       NOT NULL,
    debit_amount     NUMBER(12,2) DEFAULT 0,
    credit_amount    NUMBER(12,2) DEFAULT 0,
    CONSTRAINT fk_jed_entry   FOREIGN KEY (entry_id)   REFERENCES journal_entries(entry_id),
    CONSTRAINT fk_jed_account FOREIGN KEY (account_id) REFERENCES chart_of_accounts(account_id)
);

CREATE TABLE payments (
    payment_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id      NUMBER       NOT NULL,
    payment_date    DATE         DEFAULT SYSDATE,
    amount          NUMBER(12,2) NOT NULL,
    payment_method  VARCHAR2(30) NOT NULL,
    CONSTRAINT fk_payments_invoice FOREIGN KEY (invoice_id) REFERENCES invoices(invoice_id),
    CONSTRAINT ck_payments_method  CHECK (payment_method IN ('CASH','CREDIT_CARD','BANK_TRANSFER','PAYPAL'))
);

