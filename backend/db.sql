-- Guatemala IVA rate = 12%
CREATE OR REPLACE FUNCTION fn_calculate_iva (
    p_subtotal IN NUMBER
) RETURN NUMBER
IS
    c_iva_rate CONSTANT NUMBER := 0.12;
BEGIN
    RETURN ROUND(p_subtotal * c_iva_rate, 2);
END fn_calculate_iva;
/

